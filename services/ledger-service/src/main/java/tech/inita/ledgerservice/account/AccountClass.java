package tech.inita.ledgerservice.account;

import lombok.Getter;

/**
 * Бухгалтерская классификация счёта.
 * <p>Определяет, к какой категории бухгалтерского учёта относится счёт.</p>
 */

@Getter
public enum AccountClass {

     /**
      * Актив
      * <p>Ресурсы, контролируемые компанией, от которых ожидается экономическая выгода.
      * Нормальная сторона остатка счёта — дебитовая.</p>
      */
     ASSET(NormalSide.DEBIT),
     /**
      * Обязательство
      * <p>Деньги или другие ресурсы, которые компания обязана предоставить кому-то в будущем.
      * Нормальная сторона остатка счёта — кредитовая.</p>
      */
     LIABILITY(NormalSide.CREDIT),

     /**
      * Капитал
      * <p>Собственные средства компании после вычета обязательств из активов.
      * Нормальная сторона остатка счёта — кредитовая.</p>
      */
     EQUITY(NormalSide.CREDIT),

     /**
      * Доход
      * <p>Доход, полученный компанией в результате её деятельности.
      * Нормальная сторона остатка счёта — кредитовая.</p>
      */
     REVENUE(NormalSide.CREDIT),

     /**
      * Расход
      * <p>Затраты компании, возникающие в процессе деятельности.
      * Нормальная сторона остатка счёта — дебитовая.</p>
      */
     EXPENSE(NormalSide.DEBIT);

    private final NormalSide normalSide;

    AccountClass(NormalSide normalSide) {
        this.normalSide = normalSide;
    }

}
